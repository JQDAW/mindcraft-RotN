#!/usr/bin/env bash
# Mindcraft-RotN disposable test server: first-boot build (runs as root from cloud-init runcmd).
#
# Installed as /usr/local/sbin/rotn-test-build. Reads /etc/rotn-test/config.env (written by
# deploy/test-server.sh into the user-data). Progress goes to /var/lib/rotn-test/phase, which
# the PC polls over SSH:
#
#   packages -> pack -> [need-pack] -> unpack -> configured -> [hold] -> starting -> whitelist -> ready
#   any step can end in failed:<reason>
#
# No secrets are ever written to user-data or to this server.
set -Eeuo pipefail

CONFIG=${ROTN_TEST_CONFIG:-/etc/rotn-test/config.env}
STATE=${ROTN_TEST_STATE:-/var/lib/rotn-test}
ROOT=${ROTN_TEST_ROOT:-/opt/rotn}
SERVER=$ROOT/server
INCOMING=$ROOT/incoming
BUILD_LOG=${ROTN_TEST_BUILD_LOG:-/var/log/rotn-test-build.log}

log() { printf '[%s] %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }

phase() {
  printf '%s\n' "$1" > "$STATE/phase.tmp"
  mv -f "$STATE/phase.tmp" "$STATE/phase"
  log "phase=$1"
}

fail() {
  trap - ERR
  phase "failed:$1"
  log "FAILED: $1"
  exit 1
}

# setup_firewall: SSH (22) and Minecraft (25565) only. With ALLOW_FROM ("CIDR ...", validated on
# the PC) both ports are open to those sources only; without it, to everyone (review finding 8).
# ufw's default policy denies all other incoming traffic.
setup_firewall() {
  local ufw=${UFW_BIN:-ufw} c port
  if [[ -z ${ALLOW_FROM:-} ]]; then
    "$ufw" allow 22/tcp
    "$ufw" allow 25565/tcp
  else
    for c in $ALLOW_FROM; do
      for port in 22 25565; do "$ufw" allow proto tcp from "$c" to any port "$port"; done
    done
  fi
  "$ufw" --force enable
  printf '%s
' "${ALLOW_FROM:-any}" > "$STATE/firewall-allow-from"
}

# set_prop FILE KEY VALUE: replace KEY=... in a Java properties file, or append it.
set_prop() {
  local file=$1 key=$2 value=$3 tmp
  tmp=$(mktemp)
  awk -v k="$key" -v v="$value" '
    BEGIN { done = 0 }
    { sub(/\r$/, "") }
    index($0, k "=") == 1 { if (!done) print k "=" v; done = 1; next }
    { print }
    END { if (!done) print k "=" v }
  ' "$file" > "$tmp"
  cat "$tmp" > "$file"
  rm -f "$tmp"
}

# get_prop FILE KEY: print the value of KEY (empty if missing).
get_prop() {
  awk -v k="$2" '{ sub(/\r$/, "") } index($0, k "=") == 1 { print substr($0, length(k) + 2); exit }' "$1"
}

# The vanilla "server ready" line, e.g.
# [12:00:00] [Server thread/INFO] [minecraft/DedicatedServer]: Done (41.2s)! For help, type "help" or "?"
DONE_REGEX='\]: Done \([0-9.,]+s\)! For help'

has_done_line() { [[ -f $1 ]] && grep -Eq "$DONE_REGEX" "$1"; }

sha256_of() { sha256sum "$1" | cut -d' ' -f1; }

# wait_for_file PATH TIMEOUT_SECONDS
wait_for_file() {
  local path=$1 timeout=$2 waited=0
  while [[ ! -e $path ]]; do
    (( waited >= timeout )) && return 1
    sleep 5
    waited=$(( waited + 5 ))
  done
}

render_start_script() {
  local jar=$1
  cat <<EOF
#!/bin/sh
# Generated by rotn-test-build. Baseline: the pack's "Start Server.sh" (java -Xmx4096M -Xms256M -jar $jar nogui).
cd $SERVER
exec java -Xms${HEAP_MIN} -Xmx${HEAP_MAX} ${JVM_EXTRA} -jar $jar nogui
EOF
}

get_pack() {
  local dl=$INCOMING/download.zip pack=$INCOMING/pack.zip sum
  mkdir -p "$INCOMING"
  if [[ $PACK_SOURCE != upload && -n ${PACK_URL:-} ]]; then
    log "downloading pack from $PACK_URL"
    if curl -fL --retry 3 --retry-delay 10 --connect-timeout 30 -o "$dl" "$PACK_URL"; then
      sum=$(sha256_of "$dl")
      printf '%s\n' "$sum" > "$STATE/download-sha256"
      log "downloaded pack sha256=$sum size=$(stat -c %s "$dl")"
      if [[ $sum == "$PACK_SHA256" ]]; then
        mv -f "$dl" "$pack"
        echo download > "$STATE/pack-source"
      else
        log "downloaded pack does not match the pinned SHA-256 $PACK_SHA256; discarding it"
        rm -f "$dl"
      fi
    else
      log "pack download failed"
      rm -f "$dl"
    fi
  fi
  if [[ ! -f $pack ]]; then
    [[ $PACK_SOURCE == url ]] && fail "pack download failed or hash mismatch (pack-source=url)"
    phase need-pack
    log "waiting up to ${PACK_WAIT_SECONDS}s for the PC to upload $pack"
    wait_for_file "$pack" "$PACK_WAIT_SECONDS" || fail "timed out waiting for pack upload"
    sum=$(sha256_of "$pack")
    [[ $sum == "$PACK_SHA256" ]] || fail "uploaded pack sha256 $sum does not match pin"
    echo upload > "$STATE/pack-source"
  fi
  printf '%s\n' "$PACK_SHA256" > "$STATE/pack-sha256-verified"
}

configure_server() {
  local props=$SERVER/server.properties
  [[ -f $SERVER/$FORGE_JAR ]] || fail "expected $FORGE_JAR in the pack root"
  [[ -f $props ]] || fail "server.properties missing from the pack"
  # Fresh world every batch: the pack ships none, but make sure.
  rm -rf "$SERVER/world"
  set_prop "$props" online-mode true
  set_prop "$props" white-list true
  [[ -n ${LEVEL_SEED:-} ]] && set_prop "$props" level-seed "$LEVEL_SEED"
  if [[ $CAPTURE == 1 ]]; then
    set_prop "$props" network-compression-threshold -1
  fi
  write_whitelist > "$SERVER/whitelist.json"
  # The pack ships eula=true already; the harness re-asserts it (human-approved pack defaults).
  printf 'eula=true\n' > "$SERVER/eula.txt"
  render_start_script "$FORGE_JAR" > "$SERVER/start-test.sh"
  chmod 0755 "$SERVER/start-test.sh"
  chown -R minecraft:minecraft "$ROOT"
}

wait_for_done() {
  local logf=$SERVER/logs/latest.log waited=0
  while ! has_done_line "$logf"; do
    if (( waited > 20 )) && ! systemctl is-active --quiet rotn-server; then
      fail "server exited before Done (see $SERVER/logs and $SERVER/crash-reports)"
    fi
    (( waited >= START_TIMEOUT_SECONDS )) && fail "no Done line after ${START_TIMEOUT_SECONDS}s"
    sleep 5
    waited=$(( waited + 5 ))
  done
  grep -Em1 "$DONE_REGEX" "$logf" > "$STATE/done-line"
  log "server ready after ~${waited}s: $(cat "$STATE/done-line")"
}

# write_whitelist: WHITELIST_ENTRIES ("Name:uuid ...", resolved on the PC) -> whitelist.json.
# Written before the first start, so the server never needs its own (unreliable) name lookup.
write_whitelist() {
  local e out='[]'
  for e in $WHITELIST_ENTRIES; do
    out=$(jq -c --arg n "${e%%:*}" --arg u "${e#*:}" '. + [{uuid: $u, name: $n}]' <<< "$out")
  done
  jq . <<< "$out"
}

# check_whitelist: after the start, every configured name must still be in whitelist.json.
check_whitelist() {
  local e name missing=''
  : > "$STATE/whitelist-missing"
  for e in $WHITELIST_ENTRIES; do
    name=${e%%:*}
    if ! jq -e --arg n "$name" 'any(.[]; (.name | ascii_downcase) == ($n | ascii_downcase))' \
        "$SERVER/whitelist.json" > /dev/null 2>&1; then
      printf '%s\n' "$name" >> "$STATE/whitelist-missing"
      missing+=" $name"
    fi
  done
  [[ -z $missing ]] || fail "not whitelisted after start:$missing"
}

main() {
  mkdir -p "$STATE"
  exec >> "$BUILD_LOG" 2>&1
  trap 'fail "line $LINENO: $BASH_COMMAND"' ERR
  # shellcheck source=/dev/null
  source "$CONFIG"
  log "rotn-test-build starting for batch $BATCH_NAME"

  phase packages
  for tool in java unzip tmux curl jq ufw sha256sum; do
    command -v "$tool" > /dev/null || fail "$tool is missing (cloud-init packages step failed?)"
  done
  java -version 2>&1 | head -1 | tee "$STATE/java-version"
  grep -q 'version "1\.8' "$STATE/java-version" || fail "java is not version 8"
  setup_firewall
  id minecraft > /dev/null 2>&1 || useradd --system --home-dir "$ROOT" --shell /bin/bash minecraft
  install -d -o minecraft -g minecraft "$ROOT"

  phase pack
  get_pack

  phase unpack
  rm -rf "$SERVER"
  mkdir -p "$SERVER"
  unzip -q "$INCOMING/pack.zip" -d "$SERVER"
  rm -f "$INCOMING/pack.zip"
  configure_server
  phase configured

  if [[ $HOLD_START == 1 ]]; then
    phase hold
    log "waiting up to ${HOLD_WAIT_SECONDS}s for the PC to upload extra mods and request start"
    wait_for_file "$STATE/start-requested" "$HOLD_WAIT_SECONDS" || fail "timed out waiting for start request"
    chown -R minecraft:minecraft "$SERVER/mods"
  fi

  phase starting
  systemctl daemon-reload
  systemctl start rotn-server
  wait_for_done

  phase whitelist
  check_whitelist
  phase ready
}

if [[ ${BASH_SOURCE[0]} == "$0" ]]; then
  main "$@"
fi
