// Builds 3.3.4/common-mobs.json from the dump's biome spawn lists (spawns.json):
// the mobs a bot is most likely to meet in the overworld, for harness-ops' G2
// "common mobs are named" scenario (PR #36 reads mobs[].name).
//
// Overworld biomes: the dump has no dimension per biome, so they are chosen by name.
// The server uses level-type BIOMESOP, so the overworld is vanilla plus Biomes O' Plenty,
// plus mods that add overworld biomes (Defiled Lands, Ice and Fire's glacier).
// Score = sum of spawn weights over the overworld biomes / number of those biomes.
// Monsters and passive creatures are ranked separately and interleaved (m1, c1, m2, ...),
// so the first names cover both. Spawn-time rules (Mob Stages, light, invasions) are not
// reflected (tools/dumper/README.md), except the vanilla animals Animania removes, which are
// left out (packages/rotn-data/3.3.4/entity-overrides.json replacedByMod; G2 batch 1).
//
// Usage: node packages/rotn-data/tools/build-common-mobs.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { loadRotnData } from '../src/catalog.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '../3.3.4/common-mobs.json');

const OVERWORLD_NAMESPACES = ['minecraft', 'biomesoplenty', 'defiledlands'];
const OVERWORLD_EXTRA = ['iceandfire:glacier'];
const NOT_OVERWORLD = new Set([
    'minecraft:hell', 'minecraft:sky', 'minecraft:void',
    // Biomes O' Plenty's Nether biomes
    'biomesoplenty:corrupted_sands', 'biomesoplenty:fungi_forest', 'biomesoplenty:phantasmagoric_inferno',
    'biomesoplenty:polar_chasm', 'biomesoplenty:undergarden', 'biomesoplenty:visceral_heap',
]);
const TYPES = { monster: 'monster', creature: 'creature' };

export function buildCommonMobs({ limit = 40 } = {}) {
    const pack = loadRotnData('3.3.4');
    if (!pack.hasDump) throw new Error('no 3.3.4 dump imported');
    const biomes = Object.entries(pack.dump.spawns.biomes)
        .filter(([b]) => !NOT_OVERWORLD.has(b) && (OVERWORLD_NAMESPACES.includes(b.split(':')[0]) || OVERWORLD_EXTRA.includes(b)));
    const ranked = {};
    for (const type of Object.keys(TYPES)) {
        const score = new Map();
        const where = new Map();
        for (const [b, lists] of biomes) {
            for (const e of lists[type] ?? []) {
                // Vanilla animals Animania removes are in the biome lists but never spawn (entity-overrides.json replacedByMod).
                if (!e.entity || pack.isReplaced(e.entity)) continue;
                score.set(e.entity, (score.get(e.entity) ?? 0) + e.weight);
                if (!where.has(e.entity)) where.set(e.entity, []);
                where.get(e.entity).push(b);
            }
        }
        ranked[type] = [...score.entries()]
            .map(([name, w]) => {
                const ent = pack.entity(name);
                return { name, type, score: Math.round((w / biomes.length) * 100) / 100, biomeCount: where.get(name).length,
                    modded: !name.startsWith('minecraft:'), hostile: !!ent?.hostile, displayName: ent?.displayName ?? null };
            })
            .sort((a, b) => b.score - a.score || a.name.localeCompare(b.name));
    }
    const mobs = [];
    for (let i = 0; mobs.length < limit && (i < ranked.monster.length || i < ranked.creature.length); i++) {
        if (ranked.monster[i]) mobs.push(ranked.monster[i]);
        if (ranked.creature[i] && mobs.length < limit) mobs.push(ranked.creature[i]);
    }
    const m = pack.dump.manifest;
    return JSON.stringify({
        description: 'Mobs most likely met in the RotN 3.3.4 overworld, from the dump\'s biome spawn lists. Generated by packages/rotn-data/tools/build-common-mobs.mjs; do not edit. Monsters and passive creatures are interleaved by rank. score = summed spawn weight per overworld biome. Spawn-time rules (Mob Stages, light, invasions) are not reflected.',
        source: { dump: 'packages/rotn-data/3.3.4 (spawns.json, entities.json)', dumpedAt: m.dumpedAt, dumperJarSha256: m.dumperJar?.sha256 ?? null },
        overworldBiomes: biomes.length,
        mobs,
    }, null, 1) + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const text = buildCommonMobs();
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) { console.error('common-mobs.json is stale'); process.exit(1); }
        console.log('common-mobs.json is up to date');
    } else {
        fs.writeFileSync(OUT, text);
        console.log(`wrote ${OUT}`);
    }
}
